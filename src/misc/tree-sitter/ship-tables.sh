# usage: ship-tables.sh [LANGUAGE...]   (default: all the grammars)
#
# The tables of each grammar are generated by TeXmacs/bin/texmacs.bin of this
# tree, in a scratch TEXMACS_HOME_PATH, and written compressed by xz into
# TeXmacs/misc/tree-sitter/LANGUAGE/, under the name of the cache file
# (which holds the hash of the grammar and of the generator), replacing the
# shipped tables of an older grammar or generator. Run it again when the
# grammar or the generator (treesit-generator-version) changes: the treesit
# suite fails while the shipped tables do not match.

set -e
here=$(cd "$(dirname "$0")" && pwd)
top=$(cd "$here/../.." && pwd)
bin="$top/TeXmacs/bin/texmacs.bin"
[ -x "$bin" ] || { echo "no $bin, build TeXmacs first" >&2; exit 1; }
command -v xz > /dev/null || { echo "the xz command is needed" >&2; exit 1; }
home=$(mktemp -d "${TMPDIR:-/tmp}/ship-tables.XXXXXX")
trap 'rm -r "$home"' EXIT
if [ $# -eq 0 ]; then
  # the grammars of the program languages (tm-program-languages.scm)
  set -- $(TEXMACS_PATH="$top/TeXmacs" TEXMACS_HOME_PATH="$home" "$bin" -headless -x \
    "(begin (use-modules (treesit ts-registry))
            (display* \"LANGUAGES\" (apply string-append
              (map (lambda (l) (string-append \" \" l)) treesit-languages)) \"\\n\")
            (exit 0))" -q 2>&1 | sed -n 's/^LANGUAGES//p')
fi
for lan in "$@"; do
  echo "generating $lan..."
  TEXMACS_PATH="$top/TeXmacs" TEXMACS_HOME_PATH="$home" "$bin" -headless -x \
    "(catch #t (lambda () (use-modules (treesit ts-registry))
                          (treesit-generate-cache \"$lan\"))
               (lambda args (display* \"error: \" args \"\\n\")))
     (exit 0)" -q 2>&1 | grep "^error" || true
  file=$(ls "$home"/system/cache/tree-sitter/"$lan"-*.tsdyn 2>/dev/null | head -1)
  [ -n "$file" ] || { echo "no tables made for $lan" >&2; exit 1; }
  dest="$top/TeXmacs/misc/tree-sitter/$lan"
  rm -f "$dest"/"$lan"-*.tsdyn.xz
  # a dictionary of 16 MiB: the decoder allocates it
  xz -9e --lzma2=preset=9e,dict=16MiB -c "$file" > "$dest/$(basename "$file").xz"
  echo "$dest/$(basename "$file").xz: $(wc -c < "$dest/$(basename "$file").xz") bytes"
done
