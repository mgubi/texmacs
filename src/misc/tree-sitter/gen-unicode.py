#!/usr/bin/env python3
# Writes TeXmacs/progs/treesit/ts-unicode.scm: the character ranges of the
# Unicode properties which tree-sitter grammars use in their patterns
# (\p{L}, \p{XID_Start}...), from the unicodedata module of Python.
import sys, unicodedata

MAX = 0x110000
cats = {}
for c in range(MAX):
    cats.setdefault(unicodedata.category(chr(c)), []).append(c)

def ranges(codes):
    out = []
    for c in sorted(codes):
        if out and out[-1][1] == c:
            out[-1][1] = c + 1
        else:
            out.append([c, c + 1])
    return out

props = {}
long_names = {
    'Lu': 'Uppercase_Letter', 'Ll': 'Lowercase_Letter', 'Lt': 'Titlecase_Letter',
    'Lm': 'Modifier_Letter', 'Lo': 'Other_Letter', 'Mn': 'Nonspacing_Mark',
    'Mc': 'Spacing_Mark', 'Me': 'Enclosing_Mark', 'Nd': 'Decimal_Number',
    'Nl': 'Letter_Number', 'No': 'Other_Number', 'Pc': 'Connector_Punctuation',
    'Pd': 'Dash_Punctuation', 'Ps': 'Open_Punctuation', 'Pe': 'Close_Punctuation',
    'Pi': 'Initial_Punctuation', 'Pf': 'Final_Punctuation', 'Po': 'Other_Punctuation',
    'Sm': 'Math_Symbol', 'Sc': 'Currency_Symbol', 'Sk': 'Modifier_Symbol',
    'So': 'Other_Symbol', 'Zs': 'Space_Separator', 'Zl': 'Line_Separator',
    'Zp': 'Paragraph_Separator', 'Cc': 'Control', 'Cf': 'Format',
    'Cs': 'Surrogate', 'Co': 'Private_Use', 'Cn': 'Unassigned',
}
groups = {'L': 'Letter', 'M': 'Mark', 'N': 'Number', 'P': 'Punctuation',
          'S': 'Symbol', 'Z': 'Separator', 'C': 'Other'}
for cat, codes in cats.items():
    props[cat] = set(codes)
for g in groups:
    props[g] = set(c for cat, codes in cats.items() if cat[0] == g for c in codes)
props['LC'] = props['Lu'] | props['Ll'] | props['Lt']
# identifiers, as Python sees them (PEP 3131 uses XID_Start/XID_Continue)
props['XID_Start'] = set(c for c in range(MAX)
                         if chr(c).isidentifier() and c != 0x5f)
props['XID_Continue'] = set(c for c in range(MAX)
                            if ('a' + chr(c)).isidentifier())
props['ID_Start'] = props['L'] | props['Nl']
props['ID_Continue'] = props['ID_Start'] | props['Mn'] | props['Mc'] | props['Nd'] | props['Pc']
props['Alphabetic'] = props['L'] | props['Nl']
props['White_Space'] = set([9, 10, 11, 12, 13, 32, 0x85, 0xa0, 0x1680, 0x2028, 0x2029,
                            0x202f, 0x205f, 0x3000] + list(range(0x2000, 0x200b)))
props['Any'] = set(range(MAX))

aliases = dict(long_names)
aliases.update(groups)
aliases.update({'LC': 'Cased_Letter', 'XID_Start': 'XIDS', 'XID_Continue': 'XIDC',
                'ID_Start': 'IDS', 'ID_Continue': 'IDC', 'Alphabetic': 'Alpha',
                'White_Space': 'space'})

out = sys.stdout
out.write(''';;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;;
;; MODULE      : ts-unicode.scm
;; DESCRIPTION : Unicode properties for the patterns of tree-sitter grammars
;; COPYRIGHT   : (C) 2026  Massimiliano Gubinelli
;;
;; This software falls under the GNU general public license version 3 or later.
;; It comes WITHOUT ANY WARRANTY WHATSOEVER. For details, see the file LICENSE
;; in the root directory or <http://www.gnu.org/licenses/gpl-3.0.html>.
;;
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;

;; Generated by misc/tree-sitter/gen-unicode.py (Unicode %s): for each
;; property, its names and the bounds start end start end ... of its
;; half-open ranges of code points.

(texmacs-module (treesit ts-unicode))

(define-public ts-unicode-properties
  '(
''' % unicodedata.unidata_version)
for name in sorted(props):
    names = [name] + ([aliases[name]] if name in aliases else [])
    flat = []
    for a, b in ranges(props[name]):
        flat += [a, b]
    out.write('    ((%s)\n' % ' '.join('"%s"' % n for n in names))
    line = '     '
    for x in flat:
        s = ' %d' % x
        if len(line) + len(s) > 78:
            out.write(line + '\n')
            line = '     '
        line += s
    out.write(line + ')\n')
out.write('    ))\n')
