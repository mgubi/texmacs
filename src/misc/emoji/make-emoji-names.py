#!/usr/bin/env python3
#
# Generates TeXmacs/langs/encoding/emoji-names.scm, the names of the emoji
# in the universal encoding of TeXmacs (<emoji-grinning-face>), from the
# file emoji-test.txt of Unicode (https://unicode.org/Public/emoji/latest/):
#
#   python3 misc/emoji/make-emoji-names.py emoji-test.txt \
#     > TeXmacs/langs/encoding/emoji-names.scm
#
# Every fully-qualified emoji (a character or a whole sequence: a family
# joined by U+200D, a skin tone, a flag, a keycap) and every component (the
# skin tones and the hair styles) gets the name of its CLDR short name,
# written as the LaTeX package emoji writes it (\emoji{grinning-face}):
# in small letters, without accents, without the signs : , . ' ( ) and the
# quotes, with a hyphen for a space; "#" and "*" of the keycaps are "hash"
# and "asterisk". With --check <emoji-table.def of the package>, the names
# are compared with those of the package and the differences are listed on
# the standard error.
#
# The file is ASCII: the sequences are written as #XXXX escapes.

import re
import sys
import unicodedata

def tm_name (desc):
    s= desc
    s= s.replace ("keycap: #", "keycap: hash").replace ("keycap: *", "keycap: asterisk")
    s= unicodedata.normalize ("NFKD", s)
    s= "".join (c for c in s if not unicodedata.combining (c))
    s= s.replace ("\u2019", "").replace ("'", "")
    s= s.lower ()
    s= re.sub (r'[:,.()\u201c\u201d"]', "", s)
    s= s.replace ("&", "")
    s= re.sub (r'\s+', "-", s.strip ())
    return s

def read_test (path):
    version= "?"
    entries= []
    for line in open (path, encoding= "utf-8"):
        m= re.match (r'# Version: (\S+)', line)
        if m: version= m.group (1)
        if line.startswith ("#") or ";" not in line: continue
        codes, rest= line.split (";", 1)
        status, comment= rest.split ("#", 1)
        status= status.strip ()
        if status not in ("fully-qualified", "component"): continue
        m= re.match (r'\s*\S+\s+E\d+\.\d+\s+(.*)$', comment.rstrip ("\n"))
        if not m: raise SystemExit ("cannot read: " + line)
        entries.append ((codes.split (), m.group (1)))
    return version, entries

def read_latex (path):
    names= {}
    for line in open (path, encoding= "utf-8"):
        m= re.match (r'\\__emoji_def:nnnnn \{([^}]*)\} \{([^}]*)\}', line)
        if not m: continue
        codes= re.findall (r'\^\^\^\^\^\^([0-9a-f]{6})|\^\^\^\^([0-9a-f]{4})',
                           m.group (1))
        key= " ".join ("%X" % int (a or b, 16) for a, b in codes)
        names[key]= m.group (2)
    return names

def main (argv):
    check= None
    if len (argv) == 4 and argv[2] == "--check": check= argv[3]
    elif len (argv) != 2: raise SystemExit (__doc__)
    version, entries= read_test (argv[1])
    seen= {}
    out= []
    for codes, desc in entries:
        name= tm_name (desc)
        if not re.match (r'^[a-z0-9][a-z0-9!-]*$', name):
            raise SystemExit ("bad name " + name + " for " + desc)
        if name in seen:
            raise SystemExit ("two emoji named " + name)
        seen[name]= " ".join (c.upper () for c in codes)
        value= "".join ("#" + c.upper () for c in codes)
        out.append ('("<emoji-%s>"\t"%s")' % (name, value))
    if check is not None:
        latex= read_latex (check)
        diff= 0
        by_codes= dict ((v, k) for k, v in seen.items ())
        for key, lname in latex.items ():
            if key in by_codes and by_codes[key] != lname:
                diff += 1
                sys.stderr.write ("%s: %s (LaTeX %s)\n" %
                                  (key, by_codes[key], lname))
        sys.stderr.write ("%d names, %d in the LaTeX package, %d differ\n" %
                          (len (seen), len ([k for k in latex if k in by_codes]),
                           diff))
    print (";; The emoji of Unicode in the universal encoding of TeXmacs")
    print (";;")
    print (";; Generated by misc/emoji/make-emoji-names.py from emoji-test.txt,")
    print (";; Emoji version %s, of Unicode (https://unicode.org/Public/emoji/):" % version)
    print (";; the fully-qualified emoji and the components, named as the LaTeX")
    print (";; package emoji names them (CLDR short names). Do not edit by hand.")
    print (";;")
    print (";; Data: (C) Unicode, Inc., https://www.unicode.org/terms_of_use.html")
    print ()
    for line in out: print (line)

if __name__ == "__main__":
    main (sys.argv)
