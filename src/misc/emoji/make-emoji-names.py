#!/usr/bin/env python3
#
# Generates TeXmacs/langs/encoding/emoji-names.scm, the names of the emoji
# in the universal encoding of TeXmacs (<emoji-grinning-face>), from the
# file emoji-test.txt of Unicode (https://unicode.org/Public/emoji/latest/):
#
#   python3 misc/emoji/make-emoji-names.py emoji-test.txt \
#     > TeXmacs/langs/encoding/emoji-names.scm
#
# Every fully-qualified emoji (a character or a whole sequence: a family
# joined by U+200D, a skin tone, a flag, a keycap) and every component (the
# skin tones and the hair styles) gets the name of its CLDR short name,
# written as the LaTeX package emoji writes it (\emoji{grinning-face}):
# in small letters, without accents, without the signs : , . ' ( ) and the
# quotes, with a hyphen for a space; "#" and "*" of the keycaps are "hash"
# and "asterisk". With --check <emoji-table.def of the package>, the names
# are compared with those of the package and the differences are listed on
# the standard error. With
#
#   python3 misc/emoji/make-emoji-names.py --aliases emoji-test.txt \
#     emoji-table.def > TeXmacs/langs/encoding/emoji-latex-aliases.scm
#
# it writes the other names of the package instead (its aliases, as
# \emoji{smile}, \emoji{+1}, and its names which CLDR changed since), for
# the import of LaTeX.
#
# The file is ASCII: the sequences are written as #XXXX escapes.

import re
import sys
import unicodedata

def tm_name (desc):
    s= desc
    s= s.replace ("keycap: #", "keycap: hash").replace ("keycap: *", "keycap: asterisk")
    s= unicodedata.normalize ("NFKD", s)
    s= "".join (c for c in s if not unicodedata.combining (c))
    s= s.replace ("\u2019", "").replace ("'", "")
    s= s.lower ()
    s= re.sub (r'[:,.()\u201c\u201d"]', "", s)
    s= s.replace ("&", "")
    s= re.sub (r'\s+', "-", s.strip ())
    return s

def read_test (path):
    version= "?"
    entries= []
    for line in open (path, encoding= "utf-8"):
        m= re.match (r'# Version: (\S+)', line)
        if m: version= m.group (1)
        if line.startswith ("#") or ";" not in line: continue
        codes, rest= line.split (";", 1)
        status, comment= rest.split ("#", 1)
        status= status.strip ()
        if status not in ("fully-qualified", "component"): continue
        m= re.match (r'\s*\S+\s+E\d+\.\d+\s+(.*)$', comment.rstrip ("\n"))
        if not m: raise SystemExit ("cannot read: " + line)
        entries.append ((codes.split (), m.group (1)))
    return version, entries

def norm_codes (codes):
    # the code points, as "1F600 200D ...", whatever the digits
    return " ".join ("%X" % int (c, 16) for c in codes)

def read_latex (path):
    # the entries of emoji-table.def: (code points, name, other names)
    entries= []
    for line in open (path, encoding= "utf-8"):
        m= re.match (r'\\__emoji_def:nnnnn \{([^}]*)\} \{([^}]*)\} \{([^}]*)\}',
                     line)
        if not m: continue
        codes= re.findall (r'\^\^\^\^\^\^([0-9a-f]{6})|\^\^\^\^([0-9a-f]{4})',
                           m.group (1))
        key= norm_codes ([a or b for a, b in codes])
        aliases= [a.strip () for a in m.group (3).split (",") if a.strip ()]
        entries.append ((key, m.group (2), aliases))
    return entries

def header (what, version, extra):
    print (";; %s" % what)
    print (";;")
    print (";; Generated by misc/emoji/make-emoji-names.py from emoji-test.txt,")
    print (";; Emoji version %s, of Unicode (https://unicode.org/Public/emoji/)%s" %
           (version, extra))
    print (";; Do not edit by hand.")
    print (";;")
    print (";; Data: (C) Unicode, Inc., https://www.unicode.org/terms_of_use.html")
    print ()

def read_names (path):
    version, entries= read_test (path)
    seen= {}
    out= []
    for codes, desc in entries:
        name= tm_name (desc)
        if not re.match (r'^[a-z0-9][a-z0-9!-]*$', name):
            raise SystemExit ("bad name " + name + " for " + desc)
        if name in seen:
            raise SystemExit ("two emoji named " + name)
        seen[name]= norm_codes (codes)
        value= "".join ("#" + c.upper () for c in codes)
        out.append ('("<emoji-%s>"\t"%s")' % (name, value))
    return version, seen, out

def check (seen, path):
    latex= read_latex (path)
    by_codes= dict ((v, k) for k, v in seen.items ())
    both= [e for e in latex if e[0] in by_codes]
    diff= 0
    for key, lname, _ in both:
        if by_codes[key] != lname:
            diff += 1
            sys.stderr.write ("%s: %s (LaTeX %s)\n" % (key, by_codes[key], lname))
    missing= [e for e in latex if e[0] not in by_codes]
    for key, lname, _ in missing:
        sys.stderr.write ("%s: not fully-qualified here (LaTeX %s)\n" % (key, lname))
    sys.stderr.write ("%d names; the LaTeX package has %d entries, %d of them "
                      "here, %d with another name\n" %
                      (len (seen), len (latex), len (both), diff))

def aliases (seen, version, path):
    # the other names of the package: its aliases (GitHub shortcodes) and
    # its names which are not ours (renamed by CLDR since), when they are
    # no name of ours
    latex= read_latex (path)
    by_codes= dict ((v, k) for k, v in seen.items ())
    out= {}
    for key, lname, al in latex:
        if key not in by_codes: continue
        ours= by_codes[key]
        for a in [lname] + al:
            if a == ours or a in seen or a in out: continue
            if not re.match (r'^[a-z0-9+_!-]+$', a):
                sys.stderr.write ("left out: %s\n" % a)
                continue
            out[a]= ours
    header ("The other names of the emoji in the LaTeX package emoji",
            version, ",\n;; and emoji-table.def of the package (its aliases, after the shortcodes\n"
            ";; of GitHub, and its names which CLDR changed since): for the import of\n"
            ";; \\emoji{...}, each with the name of TeXmacs it stands for.")
    for a in sorted (out): print ('("%s"\t"%s")' % (a, out[a]))
    sys.stderr.write ("%d other names\n" % len (out))

def main (argv):
    if len (argv) == 4 and argv[1] == "--aliases":
        version, seen, _= read_names (argv[2])
        aliases (seen, version, argv[3])
        return
    if len (argv) == 4 and argv[2] == "--check":
        version, seen, out= read_names (argv[1])
        check (seen, argv[3])
    elif len (argv) == 2:
        version, seen, out= read_names (argv[1])
    else: raise SystemExit (__doc__)
    header ("The emoji of Unicode in the universal encoding of TeXmacs", version,
            ":\n;; the fully-qualified emoji and the components, named as the LaTeX\n"
            ";; package emoji names them (CLDR short names).")
    for line in out: print (line)

if __name__ == "__main__":
    main (sys.argv)
