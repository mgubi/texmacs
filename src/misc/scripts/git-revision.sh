#!/bin/sh
#
# The git commit a TeXmacs tree was built from (#753): "ebf1221c79
# 2026-11-01T00:41:00Z" (abbreviated hash, time of the commit in UTC).
#
# Usage: misc/scripts/git-revision.sh [SRCDIR]
#          prints the revision, or nothing when there is none
#        misc/scripts/git-revision.sh --header FILE [SRCDIR]
#          writes the C++ header FILE with  #define TM_GIT_REVISION "..."
#          (empty when there is none), only if its content changes, so that
#          the objects which include it are not rebuilt for nothing
#
# SRCDIR is the top of the tree (where configure is). There is no revision
# without git, in a source tarball, or in a tree which is not itself tracked
# by git (e.g. a tarball unpacked in some other repository): then everything
# stays as before ("Custom ...") and nothing fails. A shallow clone (as of
# actions/checkout) is enough: only HEAD is read.

header=
if [ "$1" = --header ]; then header="$2"; shift 2; fi
dir="${1:-.}"

rev=
if command -v git > /dev/null 2>&1 \
   && git -C "$dir" ls-files --error-unmatch configure.in > /dev/null 2>&1; then
  rev=$(TZ=UTC git -C "$dir" log -1 --abbrev=10 \
          --format='%h %cd' --date='format-local:%Y-%m-%dT%H:%M:%SZ' 2> /dev/null)
  # (only a hash and a time: no quote or backslash can come into a header)
  case "$rev" in
    [0-9a-f]*" "[0-9][0-9][0-9][0-9]-*) ;;
    *) rev= ;;
  esac
fi

if [ -z "$header" ]; then
  [ -z "$rev" ] || echo "$rev"
  exit 0
fi

new="// generated by misc/scripts/git-revision.sh: do not edit
#define TM_GIT_REVISION \"$rev\""
if [ -f "$header" ] && [ "$(cat "$header")" = "$new" ]; then exit 0; fi
printf '%s\n' "$new" > "$header"
