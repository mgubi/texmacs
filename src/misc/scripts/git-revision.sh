#!/bin/sh
#
# The git commit a TeXmacs tree was built from (#753): "ebf1221c79
# 2026-11-01T00:41:00Z" (abbreviated hash, time of the commit in UTC).
#
# Usage: misc/scripts/git-revision.sh [SRCDIR]
#          prints the revision, or nothing when there is none
#        misc/scripts/git-revision.sh --header FILE [SRCDIR]
#          writes the C++ header FILE with  #define TM_GIT_REVISION "..."
#          (empty when there is none), only if its content changes, so that
#          the objects which include it are not rebuilt for nothing
#
# SRCDIR is the top of the tree (where configure is). There is no revision
# without git, in a source tarball, or in a tree which is not itself tracked
# by git (e.g. a tarball unpacked in some other repository): then everything
# stays as before ("Custom ...") and nothing fails. A shallow clone (as of
# actions/checkout) is enough: only HEAD is read.

header=
if [ "$1" = --header ]; then header="$2"; shift 2; fi
dir="${1:-.}"

# status: ok (rev is set), none (the tree is really not tracked by git: a
# tarball, no git repository), failed (the tree is in a git checkout, but git
# gives nothing: no git program, "dubious ownership" of the checkout for the
# user who runs make install...)
rev=
status=none
in_checkout=no
d=$(cd "$dir" 2> /dev/null && pwd)
while [ -n "$d" ]; do
  if [ -e "$d/.git" ]; then in_checkout=yes; break; fi
  [ "$d" = / ] && break
  d=${d%/*}
  [ -n "$d" ] || d=/
done
if command -v git > /dev/null 2>&1; then
  if git -C "$dir" rev-parse --git-dir > /dev/null 2>&1; then
    if git -C "$dir" ls-files --error-unmatch configure.in > /dev/null 2>&1; then
      rev=$(TZ=UTC git -C "$dir" log -1 --abbrev=10 \
              --format='%h %cd' --date='format-local:%Y-%m-%dT%H:%M:%SZ' 2> /dev/null | tr -d '\r')
      # (only a hash and a time: no quote or backslash can come into a header)
      case "$rev" in
        [0-9a-f]*" "[0-9][0-9][0-9][0-9]-*) status=ok ;;
        *) rev=; status=failed ;;
      esac
    fi
  elif [ $in_checkout = yes ]; then status=failed
  fi
elif [ $in_checkout = yes ]; then status=failed
fi

if [ -z "$header" ]; then
  [ -z "$rev" ] || echo "$rev"
  exit 0
fi

# git failed in a checkout: the header of a former good run stays, with a
# warning, instead of becoming empty ("Custom" in the package)
if [ $status = failed ] && [ -f "$header" ]; then
  echo "warning: git-revision.sh: git gives no revision (git missing, or dubious ownership of the checkout?); $header kept" >&2
  exit 0
fi

new="// generated by misc/scripts/git-revision.sh: do not edit
#define TM_GIT_REVISION \"$rev\""
if [ -f "$header" ] && [ "$(tr -d '\r' < "$header")" = "$new" ]; then exit 0; fi
printf '%s\n' "$new" > "$header"
