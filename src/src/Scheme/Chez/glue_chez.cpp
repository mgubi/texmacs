static const int tmg_entry_count=
  (int) (sizeof (tmg_entries) / sizeof (tmg_entries[0]));

static_assert (sizeof (tmg_entries) / sizeof (tmg_entries[0]) <= 4096,
               "Chez Scheme: glue foreign symbol table overflow");

/* ---------------------------------------------------------------------------
 * Registration
 * ------------------------------------------------------------------------- */

static bool tmg_registered= false;

/* Called from custom_init(), i.e. inside Sbuild_heap() before the boot files
   are evaluated.  That placement is the point of this file: it is what makes
   the glue visible to boot-chez.scm and to any secondary boot file loaded
   during heap construction. */
void
initialize_glue_chez () {
  if (tmg_registered) return;
  tmg_registered= true;
  for (int i= 0; i < tmg_entry_count; i++)
    Sforeign_symbol (tmg_entries[i].name, tmg_entries[i].fn);
}

int
chez_glue_procedure_count () {
  return tmg_entry_count;
}
